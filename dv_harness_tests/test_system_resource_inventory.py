def test_address_domain_is_resolved_coarse_or_unresolved_never_assumed():
    loaded = {"status": "LOADED", "entries": [
        {"name": "CTRL", "base_address": "0x14000000", "size_bytes": 4096, "bus": "AXI4"},
        {"name": "MEM", "base_address": "0x20000000", "size_bytes": 65536, "bus": "APB"},
    ]}
    resolved = sri.resolve_address_domain(hierarchy="chip.u0", protocol="AXI4",
                                          resource_type=sri.RT_AXI_MASTER,
                                          address_map_layer=loaded)
    assert resolved["status"] == "RESOLVED"
    assert [r["name"] for r in resolved["regions"]] == ["CTRL"]

    no_bus = {"status": "LOADED", "entries": [
        {"name": "CTRL", "base_address": "0x14000000", "size_bytes": 4096}]}
    coarse = sri.resolve_address_domain(hierarchy="chip.u0", protocol="AXI4",
                                        resource_type=sri.RT_CPU_BUS_MASTER,
                                        address_map_layer=no_bus)
    assert coarse["status"] == "COARSE"

    absent = sri.resolve_address_domain(hierarchy="chip.u0", protocol="AXI4",
                                        resource_type=sri.RT_AXI_MASTER,
                                        address_map_layer={"status": "NOT_AVAILABLE"})
    assert absent["status"] == sri.UNRESOLVED
    assert absent["regions"] == []


