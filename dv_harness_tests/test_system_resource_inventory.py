MASTER_ROLE = conn.determine_role_from_port_direction("output")   # vip_role=slave_responder
SLAVE_ROLE = conn.determine_role_from_port_direction("input")     # vip_role=master_initiator


def _matrix_row(*, dut_instance, interface, vip_type, active_passive, bind_target,
                protocol=conn.PROTOCOL_NOT_CLASSIFIED, role=SLAVE_ROLE,
                fabric_side_role=conn.FABRIC_SIDE_ROLE_NOT_CLASSIFIED) -> dict:
    """One connectivity-matrix row in the real `MATRIX_COLUMNS` shape."""
    return {"dut_instance": dut_instance, "interface": interface,
            "direction": "input", "role": role, "vip_type": vip_type, "count": 1,
            "active_passive": active_passive, "bind_target": bind_target,
            "tier": conn.BindTier.T1_ALREADY_DECIDED.value, "protocol": protocol,
            "fabric_side_role": fabric_side_role}


def _write_matrix(path: Path, rows) -> Path:
    return _write(path, json.dumps({"columns": conn.MATRIX_COLUMNS, "rows": list(rows)}))


def _soc_arch_map(path: Path, *, regions, clocks=("core_clk",), resets=("core_rst_n",)) -> Path:
    """`regions` is [(name, base, size, bus)] -- `bus` may be None to model a
    real project whose SoC map has no bus column, which is what makes an
    address domain COARSE rather than RESOLVED."""
    entries = []
    for name, base, size, bus in regions:
        entry = {"name": name, "base_address": base, "size_bytes": size}
        if bus:
            entry["bus"] = bus
        entries.append(entry)
    return _write(path, json.dumps({
        "schema_version": "1.0",
        "address_map": entries,
        "clocks": [{"name": c, "frequency_mhz": 100} for c in clocks],
        "resets": [{"name": r, "active_level": "low", "clock": clocks[0]} for r in resets],
    }))


def _vip_dump(path: Path, instances) -> Path:
    """`instances` is [(instance_path, vip_type, config_fields)]."""
    return _write(path, json.dumps({"schema_version": "1.0", "vip_instances": [
        {"instance_path": p, "vip_type": t, "config_fields": dict(c)}
        for p, t, c in instances]}))


def _subsystem_sources(tmp_path: Path, name: str, *, rows, vip_instances=(),
                       regions=(("CTRL", "0x14000000", 4096, "AXI4"),),
                       clocks=("core_clk",), release_sha="sha-none",
                       **kwargs) -> sri.SubsystemResourceSources:
    """A synthetic subsystem: a real schema-valid env.manifest.json (generated
    by the real generator, not hand-written JSON) plus a connectivity matrix."""
    env = tmp_path / "generated" / name.lower()
    (env / ".dv-harness").mkdir(parents=True, exist_ok=True)
    manifest_path = env / ".dv-harness" / "env.manifest.json"
    env_manifest.generate_and_write(
        manifest_path,
        vip_config_dump_path=(_vip_dump(env / "vip_dump.json", vip_instances)
                              if vip_instances else None),
        soc_arch_map_path=_soc_arch_map(env / "soc_arch_map.json",
                                        regions=regions, clocks=clocks))
    matrix_path = _write_matrix(env / ".dv-harness" / "connectivity_matrix.json", rows)
    return sri.SubsystemResourceSources(
        subsystem_id=name, environment_root=str(env),
        env_manifest_path=str(manifest_path),
        connectivity_matrix_path=str(matrix_path),
        release_sha=release_sha, **kwargs)


# The recurring conflict fixture: TWO subsystems, each with exactly ONE active
# CPU AXI Master VIP, both binding the SAME absolute SoC hierarchy path.
SHARED_CPU_BIND = "chip.soc.cpu_axi_m"


def _two_subsystems_sharing_one_cpu_master(tmp_path: Path, *, b_active=True,
                                           b_config=None, a_config=None):
    a = _subsystem_sources(
        tmp_path, "SUBSYS_A",
        rows=[_matrix_row(dut_instance="chip.soc.cpu_axi_m", interface="axi_m",
                          vip_type="svt_axi_master_agent", active_passive="active",
                          bind_target=SHARED_CPU_BIND, protocol="AXI4",
                          role=MASTER_ROLE,
                          fabric_side_role=conn.FABRIC_SIDE_MASTER_INTERFACE)],
        vip_instances=[(SHARED_CPU_BIND, "svt_axi_master_agent",
                        a_config if a_config is not None else {"data_width": "64"})],
        release_sha="aaa111")
    b = _subsystem_sources(
        tmp_path, "SUBSYS_B",
        rows=[_matrix_row(dut_instance="chip.soc.cpu_axi_m", interface="axi_m",
                          vip_type="svt_axi_master_agent",
                          active_passive="active" if b_active else "passive",
                          bind_target=SHARED_CPU_BIND, protocol="AXI4",
                          role=MASTER_ROLE,
                          fabric_side_role=conn.FABRIC_SIDE_MASTER_INTERFACE)],
        vip_instances=[(SHARED_CPU_BIND, "svt_axi_master_agent",
                        b_config if b_config is not None else {"data_width": "64"})],
        release_sha="bbb222")
    return a, b


