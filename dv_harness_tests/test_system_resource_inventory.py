"""Tests for SYS-9..SYS-14 of the System-Level Verification Integration
workflow: `dv_harness/system_resource_inventory.py` and the one primitive it
needed from `dv_harness/connectivity.py`
(`find_active_bind_target_collisions()`).

EVERY fixture is SYNTHETIC and built inside a tmp_path: fake connectivity
matrices, fake env.manifest.json files (real, schema-valid, generated by the
real `env_manifest.generate_and_write()`), a fake vip_config dump, a fake SoC
architecture map with deliberately overlapping address ranges, a fake registry.
Nothing touches the real
`.dv-harness/soc-composer/subsystem_environment_registry.json` (legitimately
absent in this repo), and no test generates System-Level UVM source, a System
command.txt, a shared agent or a virtual sequencer -- SYS-9..14 is
discovery/analysis/planning/reporting only, and three tests assert that rather
than trusting it.

The suite is deliberately not a happy path. A dedup/conflict mechanism whose
only coverage is the case where everything agrees has no detection power, so
the cases that carry this suite are the ambiguous and conflicting ones:

  * two subsystems both claiming an ACTIVE CPU AXI Master on one bind target
    -- each subsystem's OWN connectivity self-check passes 2-for-2, and the
    duplicate is visible only to the cross-subsystem layer;
  * two subsystems whose address ranges genuinely overlap;
  * a pair whose ONLY agreeing signal is the VIP class name, which must report
    UNKNOWN/NAME_EVIDENCE_ONLY and must never be promoted;
  * two PASSIVE monitors on one interface (a duplicate, but not a hazard);
  * one physical resource the two environments configure differently;
  * two ACTIVE rows inside ONE subsystem's own matrix claiming one bind target;
  * a subsystem-specific PCIe VIP that must never be promoted, and the raise
    that fires if it ever is.
"""
