def _registered_env(tmp_path: Path, name: str, *, rows, vip_instances, command_text,
                    regions, release_sha) -> Path:
    """A synthetic subsystem environment complete enough for SYS-1 to classify
    it EXISTS_READY, carrying its own connectivity matrix and command.txt."""
    from dv_harness.uvm_generator import run_profile

    env = tmp_path / "generated" / name.lower()
    (env / ".dv-harness").mkdir(parents=True, exist_ok=True)
    _write(env / "command.txt", command_text)
    for rel in ("rtl/dut_core.sv", "env/synth_env.sv", "env/synth_agent.sv",
                "env/synth_scoreboard.sv", "vip/svt_synth_vip.sv", "Makefile",
                "filelist.f", "test/synth_test.sv", "seq/synth_seq.sv",
                "tb/tb_top.sv", "cfg/synth_config.sv", "cfg/clock_reset_map.json",
                "logs/sim.log", "regression.list", "docs/readme.md"):
        _write(env / rel, "// synthetic fixture, empty on purpose\n")
    env_manifest.generate_and_write(
        env / ".dv-harness" / "env.manifest.json",
        vip_config_dump_path=_vip_dump(env / "vip_dump.json", vip_instances),
        soc_arch_map_path=_soc_arch_map(env / "soc_arch_map.json", regions=regions))
    _write_matrix(env / ".dv-harness" / "connectivity_matrix.json", rows)
    profile = run_profile.new_empty_profile("makefile", str(env / "Makefile"), "SYNTH", "synth_")
    profile["runtime_params"] = [{"name": "WAVE", "type": "bool01", "default": "0"}]
    profile["targets"] = [{"name": "compile"}, {"name": "sim"}]
    _write(env / ".dv-harness" / "run_profile.json", json.dumps(profile))
    return env


