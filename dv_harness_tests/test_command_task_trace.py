    assert vip_leg.status == ctt.LEG_RESOLVED
    kinds = {c.kind for c in vip_leg.citations}
    assert "vip_prefix_reference" in kinds
    assert any(c.detail == "svt_usb_agent_config" for c in vip_leg.citations)


