def test_ambiguous_conflicting_task_declarations_never_reads_trace_complete(tmp_path):
    """Two genuinely different `task run_usb2_con_vip` declarations in two
    different files is a real textual ambiguity a declaration-level scan
    cannot resolve -- this must downgrade to TRACE_PARTIAL, never be silently
    picked one way or upgraded to TRACE_COMPLETE."""
    env_dir = _write_fixture_env(tmp_path)
    (env_dir / "patterns" / "usb2_con_vip_task_v2.sv").write_text(textwrap.dedent("""\
        task automatic run_usb2_con_vip();
          $display("a second, conflicting declaration of the same task name");
        endtask
        """), encoding="utf-8")
    report = ctt.trace_command("run_usb2_con_vip", env_dir, use_verible=False)
    task_leg = report.legs[ctt.LEG_TASK_MACRO]
    assert task_leg.status == ctt.LEG_AMBIGUOUS
    assert report.status == ctt.STATUS_TRACE_PARTIAL
    assert report.status != ctt.STATUS_TRACE_COMPLETE
    assert "distinct 'task run_usb2_con_vip'" in task_leg.reason


