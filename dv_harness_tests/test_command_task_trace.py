# --- real generated environment already in this repo --------------------------

def test_against_a_real_generated_environment_reports_honestly(tmp_path):
    """Against this project's own real `examples/generated_usb_real_evidence_v1/`
    (produced by this project's own generator, not by this module), tracing a
    command name that really exists there via the real registry mapping must
    not crash and must produce a real, honestly-partial-or-better report --
    never a fabricated TRACE_COMPLETE for legs this real environment does not
    carry (its dv_uvm_hook.svh bridge instance is a real TODO_PLACEHOLDER, not
    a wired bridge)."""
    real_env = ROOT / "examples" / "generated_usb_real_evidence_v1"
    if not real_env.is_dir():
        pytest.skip("real fixture environment not present in this checkout")
    report = ctt.trace_command("USB2_con_vip", real_env, use_verible=False)
    assert report.status in (ctt.STATUS_TRACE_COMPLETE, ctt.STATUS_TRACE_PARTIAL,
                              ctt.STATUS_NOT_FOUND)
    assert report.files_scanned > 0
    task_leg = report.legs.get(ctt.LEG_TASK_MACRO)
    if task_leg is not None:
        assert task_leg.status in (ctt.LEG_RESOLVED, ctt.LEG_AMBIGUOUS)


# --- CLI, driven as a real subprocess -------------------------------------------

def test_cli_json_and_exit_code(tmp_path):
    env_dir = _write_fixture_env(tmp_path)
    proc = subprocess.run(
        [sys.executable, "-m", "dv_harness.command_task_trace",
         "--env-dir", str(env_dir), "--command", "USB2_con_vip",
         "--no-verible", "--json"],
        cwd=str(ROOT), capture_output=True, text=True, timeout=60)
    assert proc.returncode == 0, proc.stderr
    payload = json.loads(proc.stdout)
    assert payload[0]["status"] == ctt.STATUS_TRACE_COMPLETE


