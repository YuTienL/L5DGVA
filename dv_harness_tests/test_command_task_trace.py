"""Tests for dv_harness/command_task_trace.py -- DE-command-name traceability
by real grep-based cross-reference over a generated environment's files.

Fixture (`_write_fixture_env`) is a small, synthetic-but-realistic generated
environment shaped after this repo's own REAL generated evidence
(`examples/generated_usb_real_evidence_v1/`): a case-dispatch pattern pool
(`dv_uvm_pattern_pool.svh`'s real shape), a handler task carrying a real
`` `CPUWRITE1B `` macro invocation and a `// VIP:` citation comment (the real
convention `USB2_con_vip.txt` uses), a `` `define ``-redirect bridge file
(`dv_uvm_hook.svh`'s real shape: `` `CPUWRITE1B `` -> `dv_uvm_cpuwrite1b`), and
a scoreboard file citing a `` `FINAL_CHECK `` macro. Nothing here is mined
from a real project's content -- it is hand-authored to exercise this
module's own four legs, matching the SHAPE of real evidence already cited in
CLAUDE.md's Bind-Location Rules / pattern-architecture skill sections.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

from dv_harness import command_task_trace as ctt

ROOT = Path(__file__).resolve().parents[1]
requires_verible = pytest.mark.skipif(
    shutil.which("verible-verilog-syntax") is None,
    reason="verible-verilog-syntax not on PATH",
)


def _write_fixture_env(tmp_path: Path) -> Path:
    env_dir = tmp_path / "generated_env"
    (env_dir / "patterns_registry").mkdir(parents=True)
    (env_dir / "patterns").mkdir(parents=True)
    (env_dir / "bind").mkdir(parents=True)
    (env_dir / "env").mkdir(parents=True)

    (env_dir / "patterns_registry" / "dv_uvm_pattern_pool.svh").write_text(textwrap.dedent("""\
        // GENERATED by dv_harness/uvm_generator/pattern_registry_generator.py
        task automatic run_selected_pattern(string pattern_name);
          case (pattern_name)
            "USB2_con_vip": run_usb2_con_vip();
            default: `uvm_fatal("PATTERN_POOL", $sformatf("Unknown pattern '%s'", pattern_name))
          endcase
        endtask
        """), encoding="utf-8")

    (env_dir / "patterns" / "usb2_con_vip_task.sv").write_text(textwrap.dedent("""\
        task automatic run_usb2_con_vip();
          `CPUWRITE1B(32'h1270_0200, 8'h10); //usb ctrl rst=1
          svt_usb_agent_config vip_cfg;
          // VIP: svt_usb_agent configure HOST role
          $display("=>Dev Ctrl init done");
        endtask
        """), encoding="utf-8")

    (env_dir / "bind" / "dv_uvm_hook.svh").write_text(textwrap.dedent("""\
        // -- macro redirect (must precede the model's task definitions) --
        `define CPUWRITE1B dv_uvm_cpuwrite1b

        task automatic dv_uvm_cpuwrite1b(input [31:0] addr, input [7:0] data);
          uvm_config_db#(int)::set(null, "*", "cpuwrite1b_addr", addr);
        endtask
        """), encoding="utf-8")

    (env_dir / "env" / "usb_scoreboard.sv").write_text(textwrap.dedent("""\
        class usb_scoreboard extends uvm_scoreboard;
          `uvm_component_utils(usb_scoreboard)
          function void check_phase(uvm_phase phase);
            `FINAL_CHECK("USB2_con_vip")
          endfunction
        endclass
        """), encoding="utf-8")

    return env_dir


# --- positive path ------------------------------------------------------------

def test_full_chain_resolves_trace_complete_via_case_dispatch(tmp_path):
    env_dir = _write_fixture_env(tmp_path)
    report = ctt.trace_command("USB2_con_vip", env_dir, use_verible=False)
    assert report.status == ctt.STATUS_TRACE_COMPLETE
    assert report.reason is None

    task_leg = report.legs[ctt.LEG_TASK_MACRO]
    assert task_leg.status == ctt.LEG_RESOLVED
    kinds = {c.kind for c in task_leg.citations}
    assert "case_dispatch" in kinds
    assert "handler_task_declaration" in kinds

    bridge_leg = report.legs[ctt.LEG_UVM_BRIDGE]
    assert bridge_leg.status == ctt.LEG_RESOLVED
    assert any(c.kind == "macro_redirect_bridge" for c in bridge_leg.citations)

    vip_leg = report.legs[ctt.LEG_VIP_API]
    assert vip_leg.status == ctt.LEG_RESOLVED
    assert any(c.kind == "vip_comment_citation" for c in vip_leg.citations)

    checker_leg = report.legs[ctt.LEG_CHECKER]
    assert checker_leg.status == ctt.LEG_RESOLVED
    assert any(c.kind == "checker_macro_call" for c in checker_leg.citations)


def test_vip_prefix_widens_the_vip_leg(tmp_path):
    env_dir = _write_fixture_env(tmp_path)
    report = ctt.trace_command("USB2_con_vip", env_dir, vip_prefixes=["svt_"], use_verible=False)
