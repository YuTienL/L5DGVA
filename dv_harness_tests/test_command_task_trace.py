# --- multi-command / exit-code plumbing ---------------------------------------

def test_trace_commands_and_overall_exit_code(tmp_path):
    env_dir = _write_fixture_env(tmp_path)
    reports = ctt.trace_commands(["USB2_con_vip", "NO_SUCH_COMMAND"], env_dir, use_verible=False)
    assert len(reports) == 2
    assert reports[0].status == ctt.STATUS_TRACE_COMPLETE
    assert reports[1].status == ctt.STATUS_NOT_FOUND
    assert ctt.overall_exit_code(reports) == 1

    blocked_reports = [ctt.trace_command("x", tmp_path / "nope", use_verible=False)]
    assert ctt.overall_exit_code(blocked_reports) == 2

    complete_reports = [ctt.trace_command("USB2_con_vip", env_dir, use_verible=False)]
    assert ctt.overall_exit_code(complete_reports) == 0


